-- Ejecutar manualmente con psql; esquema inicial para una base vacía.
BEGIN;
CREATE TABLE cliente (
 id_cliente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(150) NOT NULL CHECK (btrim(nombre)<>''),
 correo VARCHAR(254) NOT NULL UNIQUE CHECK (correo=lower(btrim(correo))),
 password_hash VARCHAR(255) NOT NULL
);
CREATE TABLE marca (id_marca BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,nombre VARCHAR(150) NOT NULL UNIQUE);
CREATE TABLE producto (
 id_producto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_marca BIGINT NOT NULL REFERENCES marca,
 nombre VARCHAR(255) NOT NULL, descripcion VARCHAR(255),
 tipo_producto VARCHAR(255) NOT NULL CHECK(tipo_producto IN ('MOTO','ACCESORIO','REFACCION')),
 activo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE ficha_moto (
 id_producto BIGINT PRIMARY KEY REFERENCES producto,
 anio INTEGER CHECK(anio>1900),cilindrada_cc INTEGER CHECK(cilindrada_cc>0),
 motor VARCHAR(255),frenos VARCHAR(255),tanque_litros NUMERIC(6,2) CHECK(tanque_litros>0)
);
CREATE TABLE ficha_accesorio (id_producto BIGINT PRIMARY KEY REFERENCES producto,tipo_uso VARCHAR(255) NOT NULL);
CREATE TABLE ficha_refaccion (id_producto BIGINT PRIMARY KEY REFERENCES producto,compatibilidad VARCHAR(255) NOT NULL);
CREATE TABLE producto_imagen (
 id_imagen BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_producto BIGINT NOT NULL REFERENCES producto,imagen_url VARCHAR(255) NOT NULL,orden INTEGER NOT NULL CHECK(orden>=0),UNIQUE(id_producto,orden)
);
CREATE TABLE sku (
 id_sku BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_producto BIGINT NOT NULL REFERENCES producto,codigo_sku VARCHAR(255) NOT NULL UNIQUE,
 talla VARCHAR(255),color VARCHAR(255),precio_mxn NUMERIC(12,2) NOT NULL CHECK(precio_mxn>=0),
 stock INTEGER NOT NULL CHECK(stock>=0),activo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE carrito_item (
 id_cliente BIGINT NOT NULL REFERENCES cliente,id_sku BIGINT NOT NULL REFERENCES sku,
 cantidad INTEGER NOT NULL CHECK(cantidad>0),PRIMARY KEY(id_cliente,id_sku)
);
CREATE TABLE intento_confirmacion (
 id_intento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_cliente BIGINT NOT NULL REFERENCES cliente,referencia_confirmacion VARCHAR(100) NOT NULL,
 resumen_hash VARCHAR(255) NOT NULL,resultado VARCHAR(255) NOT NULL CHECK(resultado IN ('APROBADO','RECHAZADO')),
 fecha_intento TIMESTAMPTZ NOT NULL,UNIQUE(id_cliente,referencia_confirmacion),UNIQUE(id_intento,id_cliente)
);
CREATE TABLE pedido (
 id_pedido BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_cliente BIGINT NOT NULL REFERENCES cliente,id_intento BIGINT NOT NULL UNIQUE REFERENCES intento_confirmacion,
 folio VARCHAR(255) NOT NULL UNIQUE,fecha TIMESTAMPTZ NOT NULL,estado VARCHAR(255) NOT NULL CHECK(estado='CONFIRMADO'),
 total_mxn NUMERIC(12,2) NOT NULL CHECK(total_mxn>=0),nombre_destinatario VARCHAR(150) NOT NULL,
 telefono VARCHAR(20) NOT NULL,direccion VARCHAR(500) NOT NULL,localidad VARCHAR(150) NOT NULL,
 estado_entrega VARCHAR(100) NOT NULL,codigo_postal VARCHAR(5) NOT NULL CHECK(codigo_postal ~ '^[0-9]{5}$'),
 FOREIGN KEY(id_intento,id_cliente) REFERENCES intento_confirmacion(id_intento,id_cliente)
);
CREATE TABLE pedido_detalle (
 id_detalle BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,id_pedido BIGINT NOT NULL REFERENCES pedido,
 id_sku BIGINT NOT NULL REFERENCES sku,nombre_congelado VARCHAR(255) NOT NULL,marca_congelada VARCHAR(255) NOT NULL,
 descripcion_congelada VARCHAR(255),codigo_sku_congelado VARCHAR(255) NOT NULL,talla_congelada VARCHAR(255),color_congelado VARCHAR(255),
 precio_unitario_mxn NUMERIC(12,2) NOT NULL CHECK(precio_unitario_mxn>=0),cantidad INTEGER NOT NULL CHECK(cantidad>0),
 subtotal_mxn NUMERIC(12,2) NOT NULL CHECK(subtotal_mxn=precio_unitario_mxn*cantidad),UNIQUE(id_pedido,id_sku)
);
CREATE INDEX sku_producto_idx ON sku(id_producto);
CREATE INDEX pedido_cliente_fecha_idx ON pedido(id_cliente,fecha DESC);
CREATE INDEX pedido_detalle_pedido_idx ON pedido_detalle(id_pedido);
-- Restricción diferida: permite insertar producto y ficha dentro de la misma transacción.
CREATE FUNCTION validar_ficha() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE pid BIGINT; tipo TEXT; n INTEGER;
BEGIN
 IF TG_OP='UPDATE' AND OLD.id_producto<>NEW.id_producto THEN
  RAISE EXCEPTION 'No se permite cambiar la identidad de un producto o ficha';
 END IF;
 IF TG_OP='DELETE' THEN pid:=OLD.id_producto; ELSE pid:=NEW.id_producto; END IF;
 SELECT tipo_producto INTO tipo FROM producto WHERE id_producto=pid;
 IF NOT FOUND THEN RETURN NULL; END IF;
 SELECT (SELECT count(*) FROM ficha_moto WHERE id_producto=pid)+(SELECT count(*) FROM ficha_accesorio WHERE id_producto=pid)+(SELECT count(*) FROM ficha_refaccion WHERE id_producto=pid) INTO n;
 IF n<>1 OR (tipo='MOTO' AND NOT EXISTS(SELECT 1 FROM ficha_moto WHERE id_producto=pid)) OR (tipo='ACCESORIO' AND NOT EXISTS(SELECT 1 FROM ficha_accesorio WHERE id_producto=pid)) OR (tipo='REFACCION' AND NOT EXISTS(SELECT 1 FROM ficha_refaccion WHERE id_producto=pid)) THEN
  RAISE EXCEPTION 'El producto % debe tener exactamente la ficha correspondiente a su tipo',pid;
 END IF;
 RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER producto_ficha AFTER INSERT OR UPDATE OR DELETE ON producto DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION validar_ficha();
CREATE CONSTRAINT TRIGGER moto_ficha AFTER INSERT OR UPDATE OR DELETE ON ficha_moto DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION validar_ficha();
CREATE CONSTRAINT TRIGGER accesorio_ficha AFTER INSERT OR UPDATE OR DELETE ON ficha_accesorio DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION validar_ficha();
CREATE CONSTRAINT TRIGGER refaccion_ficha AFTER INSERT OR UPDATE OR DELETE ON ficha_refaccion DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION validar_ficha();
COMMIT;
